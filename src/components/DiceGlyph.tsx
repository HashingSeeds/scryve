type Point = readonly [number, number]

// why: these are the shapes the old one-and-a-half-unit round stroke drew, so the faces keep their weight and soft corners.
const SHAPE_GROWTH = 0.75
const CORNER_RADIUS = 1.1

function roundedPolygon(points: readonly Point[]) {
  const area = points.reduce((sum, [x, y], i) => {
    const [nx, ny] = points[(i + 1) % points.length]
    return sum + x * ny - nx * y
  }, 0)
  const outward = area > 0 ? -1 : 1
  const normal = ([ax, ay]: Point, [bx, by]: Point): Point => {
    const length = Math.hypot(bx - ax, by - ay)
    return [(outward * (by - ay)) / length, (outward * -(bx - ax)) / length]
  }
  const grown = points.map((point, i): Point => {
    const before = normal(points[(i + points.length - 1) % points.length], point)
    const after = normal(point, points[(i + 1) % points.length])
    const scale = SHAPE_GROWTH / (1 + before[0] * after[0] + before[1] * after[1])
    return [point[0] + (before[0] + after[0]) * scale, point[1] + (before[1] + after[1]) * scale]
  })
  const toward = ([ax, ay]: Point, [bx, by]: Point): Point => {
    const length = Math.hypot(bx - ax, by - ay)
    const t = Math.min(CORNER_RADIUS / length, 0.5)
    return [ax + (bx - ax) * t, ay + (by - ay) * t]
  }
  const at = ([x, y]: Point) => `${x.toFixed(2)} ${y.toFixed(2)}`
  return (
    grown
      .map((corner, i) => {
        const entry = toward(corner, grown[(i + grown.length - 1) % grown.length])
        const exit = toward(corner, grown[(i + 1) % grown.length])
        return `${i === 0 ? "M" : "L"}${at(entry)}Q${at(corner)} ${at(exit)}`
      })
      .join("") + "Z"
  )
}

